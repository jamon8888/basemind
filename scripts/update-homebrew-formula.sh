#!/usr/bin/env bash
set -euo pipefail

# update-homebrew-formula.sh <version> <checksums-file> [legal-formula-out]
#
# Emits two Homebrew formulae from the SAME release checksums file
# (`basemind_<version>_checksums.txt`), each in its own file:
#   * stdout                       -> Formula/basemind.rb (unchanged full profile)
#   * <legal-formula-out>          -> Formula/basemind-hacienda-legal.rb
#                                     (confidential profile, explicit name)
# Default output path is basemind-hacienda-legal.rb next to the checksums file.
# Both profiles, their .tar.gz/.zip archives and any .exe/.dmg installers ship
# in the same tagged release; a missing checksum is fatal before anything is written.

if [ $# -lt 2 ] || [ $# -gt 3 ]; then
  echo "Usage: $0 <version> <checksums-file> [legal-formula-out]" >&2
  exit 1
fi

VERSION="$1"
SUMS="$2"
LEGAL_OUT="${3:-$(dirname "$SUMS")/basemind-hacienda-legal.rb}"

BASE="https://github.com/Goldziher/basemind/releases/download/v${VERSION}"
FULL_STEM="basemind"
LEGAL_STEM="basemind-hacienda-legal"

sha_for() {
  awk -v f="$1" '{n=$NF; sub(/^[*]/, "", n); if (n == f) print $1}' "$SUMS"
}

FULL_MAC_ARM="$(sha_for "${FULL_STEM}-aarch64-apple-darwin.tar.gz")"
FULL_MAC_X64="$(sha_for "${FULL_STEM}-x86_64-apple-darwin.tar.gz")"
FULL_LINUX_ARM="$(sha_for "${FULL_STEM}-aarch64-unknown-linux-gnu.tar.gz")"
FULL_LINUX_X64="$(sha_for "${FULL_STEM}-x86_64-unknown-linux-gnu.tar.gz")"
LEGAL_MAC_ARM="$(sha_for "${LEGAL_STEM}-aarch64-apple-darwin.tar.gz")"
LEGAL_MAC_X64="$(sha_for "${LEGAL_STEM}-x86_64-apple-darwin.tar.gz")"
LEGAL_LINUX_ARM="$(sha_for "${LEGAL_STEM}-aarch64-unknown-linux-gnu.tar.gz")"
LEGAL_LINUX_X64="$(sha_for "${LEGAL_STEM}-x86_64-unknown-linux-gnu.tar.gz")"

# Resolve and validate BOTH profiles before emitting either file, so a partial
# release can never leave a stale formula behind.
for pair in \
  "basemind-aarch64-apple-darwin.tar.gz:${FULL_MAC_ARM}" \
  "basemind-x86_64-apple-darwin.tar.gz:${FULL_MAC_X64}" \
  "basemind-aarch64-unknown-linux-gnu.tar.gz:${FULL_LINUX_ARM}" \
  "basemind-x86_64-unknown-linux-gnu.tar.gz:${FULL_LINUX_X64}" \
  "basemind-hacienda-legal-aarch64-apple-darwin.tar.gz:${LEGAL_MAC_ARM}" \
  "basemind-hacienda-legal-x86_64-apple-darwin.tar.gz:${LEGAL_MAC_X64}" \
  "basemind-hacienda-legal-aarch64-unknown-linux-gnu.tar.gz:${LEGAL_LINUX_ARM}" \
  "basemind-hacienda-legal-x86_64-unknown-linux-gnu.tar.gz:${LEGAL_LINUX_X64}"; do
  asset="${pair%%:*}"
  digest="${pair#*:}"
  if [ -z "$digest" ]; then
    echo "missing SHA-256 checksum for ${asset} in ${SUMS} — refusing to generate a partial formula" >&2
    exit 1
  fi
done

# 1. The existing full-profile formula is unchanged: stdout stays valid as the
#    single `basemind.rb` the tap already carries.
cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/update-homebrew-formula.sh — do not edit by hand.
class Basemind < Formula
  desc "Full AI context layer over MCP — code-map, document RAG, memory, web, git"
  homepage "https://github.com/Goldziher/basemind"
  version "${VERSION}"
  license "MIT"

  on_macos do
    on_arm do
      url "${BASE}/basemind-aarch64-apple-darwin.tar.gz"
      sha256 "${FULL_MAC_ARM}"
    end
    on_intel do
      url "${BASE}/basemind-x86_64-apple-darwin.tar.gz"
      sha256 "${FULL_MAC_X64}"
    end
  end

  on_linux do
    on_arm do
      url "${BASE}/basemind-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "${FULL_LINUX_ARM}"
    end
    on_intel do
      url "${BASE}/basemind-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${FULL_LINUX_X64}"
    end
  end

  def install
    # Archive root holds the binary + lib/ of bundled native libs (plus a co-located
    # libonnxruntime.dylib on Intel macOS); the binary's rpath resolves lib/ relative
    # to its own location and ort resolves the ONNX dylib relative to the executable,
    # so keep them together in libexec and expose the binary on PATH via a symlink.
    libexec.install Dir["*"]
    bin.install_symlink libexec/"basemind"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/basemind --version")
  end
end
EOF

# 2. The confidential profile gets its own formula file, so `brew install
#    Goldziher/tap/basemind-hacienda-legal` resolves a distinct class with
#    distinct assets instead of colliding in basemind.rb.
cat >"$LEGAL_OUT" <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/update-homebrew-formula.sh — do not edit by hand.
# Confidential profile: documents + memory + NER + GraphRAG, no code/comms/crawl.
# Both profiles ship in the same v${VERSION} release.
class BasemindHaciendaLegal < Formula
  desc "Confidential documents + memory + NER + GraphRAG profile (no code/comms/crawl)"
  homepage "https://github.com/Goldziher/basemind"
  version "${VERSION}"
  license "MIT"

  on_macos do
    on_arm do
      url "${BASE}/basemind-hacienda-legal-aarch64-apple-darwin.tar.gz"
      sha256 "${LEGAL_MAC_ARM}"
    end
    on_intel do
      # Universal macOS coverage: the Intel asset is built on macOS 15 and
      # requires macOS 15 (Sequoia) or newer; arm64 covers Apple Silicon.
      url "${BASE}/basemind-hacienda-legal-x86_64-apple-darwin.tar.gz"
      sha256 "${LEGAL_MAC_X64}"
    end
  end

  on_linux do
    on_arm do
      url "${BASE}/basemind-hacienda-legal-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "${LEGAL_LINUX_ARM}"
    end
    on_intel do
      url "${BASE}/basemind-hacienda-legal-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${LEGAL_LINUX_X64}"
    end
  end

  def install
    libexec.install Dir["*"]
    bin.install_symlink libexec/"basemind"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/basemind --version")
  end
end
EOF

echo "wrote ${LEGAL_OUT}" >&2
